/* canonicalise a SAN list with chess.js and return the move objects */
function canonicalMoves(sans) {
  const game = new Chess();
  const out = [];
  for (let i = 0; i < sans.length; i++) {
    const m = game.move(sans[i]);
    if (!m) {
      const err = new Error(`illegal SAN "${sans[i]}" at ply ${i} (full line: ${sans.join(' ')})`);
      err.ply = i;
      throw err;
    }
    out.push(m.san);
  }
  return out;
}

(async () => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    /* teaching metadatum: line names */
    await client.query('ALTER TABLE opening_lines ADD COLUMN IF NOT EXISTS name TEXT');

    let totalCreated = 0;
    let totalSkipped = 0;
    let mainsFixed = 0;

    for (const def of COURSES) {
      /* course row */
      let cid = (await client.query('SELECT id FROM opening_courses WHERE slug = $1', [def.slug])).rows[0]?.id;
      if (!cid) {
        const guess = { title: def.slug, side: 'white', description: '', tags: [], difficulty: 'Easy', ecoCode: null, guide: '' };
        const ins = await client.query(
          `INSERT INTO opening_courses (slug, title, side, description, tags, difficulty, eco_code, guide, is_official)
           VALUES ($1,$2,$3,$4,$5,$6,$7,$8,true) RETURNING id`,
          [def.slug, guess.title, guess.side, guess.description, guess.tags, guess.difficulty, guess.ecoCode, guess.guide]
        );
        cid = ins.rows[0].id;
        console.log('created course row:', def.slug);
      }

      /* existing lines: canonical moves -> row */
      const existRes = await client.query(
        'SELECT id, moves, is_main_line, parent_line_id, name FROM opening_lines WHERE course_id = $1', [cid]
      );
      const byMoves = new Map();
      let existingMain = null;
      for (const row of existRes.rows) {
        let canon = row.moves;
        try { canon = canonicalMoves(row.moves); } catch (e) { /* leave as-is if already legal */ }
        byMoves.set(JSON.stringify(canon), { id: row.id, main: row.is_main_line, name: row.name, parentId: row.parent_line_id });
        if (row.is_main_line) existingMain = row.id;
      }

      const aliasToId = new Map(); /* key -> db id */
      const inserts = [];
      let count = 0;

      for (const [key, line] of Object.entries(def.lines)) {
        let canon;
        try {
          canon = canonicalMoves(line.moves);
        } catch (e) {
          throw new Error(`${def.slug}:[${key}] — ${e.message}`);
        }
        if (line.ex && line.ex.length !== canon.length) {
          throw new Error(
            `${def.slug}:[${key}] — explanation count ${line.ex.length} != move count ${canon.length}`
          );
        }
        const keyJson = JSON.stringify(canon);
        const existing = byMoves.get(keyJson);

        if (existing) {
          /* name / main-line maintenance for previously-seeded rows */
          if (!existing.name && line.name) {
            await client.query('UPDATE opening_lines SET name = $1 WHERE id = $2', [line.name, existing.id]);
            existing.name = line.name;
          }
          const parentId = line.p ? aliasToId.get(line.p) : null;
          if (parentId && !existing.parentId) {
            await client.query('UPDATE opening_lines SET parent_line_id = $1 WHERE id = $2', [parentId, existing.id]);
            existing.parentId = parentId;
          }
          if (existing.main !== true && line.main === true && !existingMain) {
            await client.query('UPDATE opening_lines SET is_main_line = true WHERE id = $2', [existing.id]);
            existingMain = existing.id;
            mainsFixed += 1;
          }
          aliasToId.set(key, existing.id);
          totalSkipped += 1;
          continue;
        }

        const parentId = line.p ? aliasToId.get(line.p) : null;
        inserts.push({
          key,
          name: line.name,
          moves: canon,
          ex: (line.ex || []).map((text, moveIndex) => ({ moveIndex, text })),
          main: line.main === true && !existingMain,
          parentId,
          orderIndex: key === 'main' ? 0 : count + 1,
        });
        aliasToId.set(key, /* place-holder id filled after insert */ null);
        count += 1;
      }

      for (const ins of inserts) {
        const r = await client.query(
          `INSERT INTO opening_lines (course_id, moves, explanations, is_main_line, parent_line_id, order_index, name)
           VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING id`,
          [cid, ins.moves, JSON.stringify(ins.ex), ins.main, ins.parentId, ins.orderIndex, ins.name]
        );
        aliasToId.set(ins.key, r.rows[0].id);
        if (ins.main) existingMain = r.rows[0].id;
        totalCreated += 1;
      }

      /* bump updated_at so "recently updated" reflects the expansion */
      if (inserts.length) {
        await client.query('UPDATE opening_courses SET updated_at = NOW() WHERE id = $1', [cid]);
      }

      const finalCount = (await client.query('SELECT COUNT(*)::int AS c FROM opening_lines WHERE course_id = $1', [cid])).rows[0].c;
      console.log(`${def.slug}: ${finalCount} lines (${inserts.length} new, ${Object.keys(def.lines).length - inserts.length} matched)`);
    }

    await client.query('COMMIT');
    console.log(`\nDone — ${totalCreated} lines appended, ${totalSkipped} already present. Progress records untouched.`);
  } catch (e) {
    await client.query('ROLLBACK');
    console.error('\nSEED FAILED, rolled back:', e.message);
    process.exitCode = 1;
  } finally {
    client.release();
    await pool.end();
  }
})().catch((e) => { console.error(e); process.exit(1); });