const express = require('express');
const router = express.Router();
const ctrl = require('../controllers/puzzleController');
const authMiddleware = require('../middleware/authMiddleware');
const roleMiddleware = require('../middleware/roleMiddleware');
const requireFeature = require('../middleware/requireFeature');

router.get('/', authMiddleware, ctrl.listPuzzles);
router.get('/themes', ctrl.themeCategories);
router.get('/assigned', authMiddleware, roleMiddleware('student'), requireFeature('puzzle_trainer'), ctrl.listStudentAssignedPuzzles);
router.get('/my-assignments', authMiddleware, roleMiddleware('student'), requireFeature('puzzle_trainer'), ctrl.listStudentPuzzleAssignments);
router.post('/:id/submit-assignment', authMiddleware, roleMiddleware('student'), requireFeature('puzzle_trainer'), ctrl.submitPuzzleAssignment);
router.get('/listing', authMiddleware, roleMiddleware('admin'), ctrl.listingPuzzles);
router.get('/sets', authMiddleware, roleMiddleware('admin'), ctrl.listSets);
router.get('/sets/:setCode', authMiddleware, roleMiddleware('admin'), ctrl.listSetPuzzles);
router.patch('/sets/:setCode', authMiddleware, roleMiddleware('admin'), ctrl.renameSet);
router.delete('/sets/:setCode', authMiddleware, roleMiddleware('admin'), ctrl.deleteSet);
router.post('/sets/:setCode/reorder', authMiddleware, roleMiddleware('admin'), ctrl.reorderSetPuzzles);
router.patch('/sets/:setCode/puzzles/:id', authMiddleware, roleMiddleware('admin'), ctrl.updateSetPuzzle);
router.post('/sets/:setCode/puzzles', authMiddleware, roleMiddleware('admin'), ctrl.addSetPuzzle);
router.post('/import-csv-set', authMiddleware, roleMiddleware('admin'), ctrl.importCSVSet);
router.get('/import-jobs/:id', authMiddleware, roleMiddleware('admin'), ctrl.getImportJob);
router.get('/import-jobs/:id/errors.csv', authMiddleware, roleMiddleware('admin'), ctrl.downloadImportErrors);
router.get('/search', authMiddleware, roleMiddleware('admin'), ctrl.searchPuzzles);
router.get('/titles', authMiddleware, roleMiddleware('admin'), ctrl.getPuzzleTitles);
router.post('/assign-to-students', authMiddleware, roleMiddleware('admin'), ctrl.assignPuzzlesToStudents);
router.post('/', authMiddleware, roleMiddleware('admin'), ctrl.createPuzzle);
router.post('/bulk-import', authMiddleware, roleMiddleware('admin'), ctrl.bulkImport);
router.post('/import-csv', authMiddleware, roleMiddleware('admin'), ctrl.importCSV);
router.post('/unpublish-all', authMiddleware, roleMiddleware('admin'), ctrl.unpublishAll);
router.get('/assignments/results', authMiddleware, roleMiddleware('admin'), ctrl.getAssignmentResults);
router.get('/completion', authMiddleware, roleMiddleware('admin'), ctrl.getCompletion);
router.get('/student-report', authMiddleware, roleMiddleware('admin'), ctrl.getStudentPuzzleReport);
router.get('/:id', ctrl.getPuzzle);
router.get('/:id/assignments', authMiddleware, roleMiddleware('admin'), ctrl.getAssignments);
router.get('/:id/results', authMiddleware, roleMiddleware('admin'), ctrl.getPuzzleResults);
router.post('/:id/assign', authMiddleware, roleMiddleware('admin'), ctrl.assignPuzzle);
router.delete('/:id', authMiddleware, roleMiddleware('admin'), ctrl.deletePuzzle);
router.patch('/:id/publish', authMiddleware, roleMiddleware('admin'), ctrl.togglePublish);
router.post('/:id/attempt', authMiddleware, roleMiddleware('student'), requireFeature('puzzle_trainer'), ctrl.attemptPuzzle);

module.exports = router;